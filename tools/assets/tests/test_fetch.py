"""fetch.py against the spec scenarios of "Pinned third-party files": verify passes, a tampered file fails, a
non-free licence is refused, an unlisted file is flagged, a CREDITS.md mismatch is flagged; plus fetch and --add
through a local server."""
import hashlib
import io
import json
import zipfile

import fetch
from conftest import MAPS, SET_ID, THIRD_PARTY, content, make_root, run

SET_DIR = THIRD_PARTY / "polyhaven" / SET_ID


def manifest(root):
    return json.loads((root / "tools" / "assets" / "manifest.json").read_text(encoding="utf-8"))


def test_verify_passes_on_clean_root(root, capsys):
    assert run("--verify", "--root", root) == 0
    assert "OK" in capsys.readouterr().out


def test_tampered_file_fails_verify_naming_it(root, capsys):
    path = root / SET_DIR / MAPS["diffuse"]
    data = bytearray(path.read_bytes())
    data[10] ^= 0x01
    path.write_bytes(data)
    assert run("--verify", "--root", root) == 1
    assert f"{SET_DIR.as_posix()}/{MAPS['diffuse']}: SHA-256 differs" in capsys.readouterr().out


def test_missing_file_fails_verify(root, capsys):
    (root / SET_DIR / MAPS["normal"]).unlink()
    assert run("--verify", "--root", root) == 1
    assert f"{MAPS['normal']}: missing" in capsys.readouterr().out


def test_non_free_licence_refused_by_fetch_and_verify(tmp_path, capsys):
    root = make_root(tmp_path, licence="CC-BY-NC")
    assert run("--verify", "--root", root) == 1
    assert "licence 'CC-BY-NC' is not free" in capsys.readouterr().out
    assert run(SET_ID, "--root", root) == 1
    assert run("--all", "--root", root) == 1
    assert run("--credits", "--root", root) == 1
    assert not (root / "CREDITS.md").exists()


def test_unlisted_file_flagged_but_unity_meta_allowed(root, capsys):
    (root / SET_DIR / (MAPS["diffuse"] + ".meta")).write_text("fileFormatVersion: 2\n")
    (root / THIRD_PARTY / "polyhaven" / (SET_ID + ".meta")).write_text("folderAsset: yes\n")
    assert run("--verify", "--root", root) == 0
    stray = root / THIRD_PARTY / "ambientcg" / "Stray001" / "Stray001_1K-PNG_Color.png"
    stray.parent.mkdir(parents=True)
    stray.write_bytes(b"x")
    assert run("--verify", "--root", root) == 1
    assert "ambientcg/Stray001/Stray001_1K-PNG_Color.png: not in the manifest" in capsys.readouterr().out


def test_credits_mismatch_flagged_and_regenerated(root, capsys):
    credits = root / "CREDITS.md"
    generated = credits.read_text(encoding="utf-8")
    assert "Fake Set (1k)" in generated and "A. Tester" in generated and f"polyhaven.com/a/{SET_ID}" in generated
    assert "Generated by" in generated and "CC0 1.0" in generated
    credits.write_text(generated.replace("A. Tester", "Someone Else"), encoding="utf-8")
    assert run("--verify", "--root", root) == 1
    assert "CREDITS.md: does not match the manifest" in capsys.readouterr().out
    assert run("--credits", "--root", root) == 0
    assert credits.read_text(encoding="utf-8") == generated
    credits.unlink()
    assert run("--verify", "--root", root) == 1


def test_fetch_restores_a_missing_file_and_refuses_a_changed_upstream(tmp_path, server, capsys):
    base, www = server
    root = make_root(tmp_path, base_url=f"{base}/dl")
    (www / "dl").mkdir()
    for name in MAPS.values():
        (www / "dl" / name).write_bytes(content(name))
    path = root / SET_DIR / MAPS["diffuse"]
    path.unlink()
    assert run(SET_ID, "--verify", "--root", root) == 0
    assert path.read_bytes() == content(MAPS["diffuse"])
    assert run("polyhaven:" + SET_ID, "--root", root) == 0  # nothing missing: no download, still fine
    assert run("no_such_set", "--root", root) == 1

    (www / "dl" / MAPS["diffuse"]).write_bytes(b"upstream changed")
    path.unlink()
    assert run("--all", "--root", root) == 1
    assert "differs from its pin, upstream changed" in capsys.readouterr().out
    assert not path.exists() and not list(path.parent.glob("*.part"))


def test_add_polyhaven_prefers_png_and_pins_every_map(root, server, capsys):
    base, www = server
    (www / "files").mkdir()
    (www / "info").mkdir()
    (www / "dl").mkdir()
    files_api = {}
    for map_name, ph_key in fetch.POLYHAVEN_KEYS.items():
        files_api[ph_key] = {}
        for res in ("1k", "2k"):
            files_api[ph_key][res] = {}
            for ext in ("jpg", "png"):
                name = f"new_set_{ph_key.lower()}_{res}.{ext}"
                (www / "dl" / name).write_bytes(content(name))
                files_api[ph_key][res][ext] = {"url": f"{base}/dl/{name}", "size": len(content(name)), "md5": ""}
    (www / "files" / "new_set").write_text(json.dumps(files_api))
    (www / "info" / "new_set").write_text(json.dumps({"name": "New Set", "authors": {"Zed Scanner": "All",
                                                                                     "Amy Author": "Photos"}}))
    assert run("--add", "polyhaven:new_set", "--res", "2k", "--root", root) == 0

    entries = {e["id"]: e for e in manifest(root)["entries"]}
    assert set(entries) == {SET_ID, "new_set"}
    new = entries["new_set"]
    assert (new["title"], new["author"], new["licence"], new["resolution"]) == ("New Set", "Amy Author, Zed Scanner",
                                                                                 "CC0", "2k")
    assert new["page"] == "https://polyhaven.com/a/new_set"
    assert new["destination"] == f"{THIRD_PARTY.as_posix()}/polyhaven/new_set"
    assert [f["map"] for f in new["files"]] == ["diffuse", "normal", "roughness", "ao"]  # no displacement unasked
    for f in new["files"]:
        assert f["name"].endswith("_2k.png") and f["url"] == f"{base}/dl/{f['name']}"
        on_disk = root / THIRD_PARTY / "polyhaven" / "new_set" / f["name"]
        assert on_disk.read_bytes() == content(f["name"]) and f["bytes"] == len(content(f["name"]))
        assert f["sha256"] == fetch.sha256(on_disk)
    credits = (root / "CREDITS.md").read_text(encoding="utf-8")
    assert "New Set (2k)" in credits and "Amy Author, Zed Scanner" in credits
    assert run("--verify", "--root", root) == 0
    assert run("--add", "polyhaven:new_set", "--res", "2k", "--root", root) == 1  # already pinned
    assert "already in the manifest" in capsys.readouterr().out


def test_add_ambientcg_pins_the_zip_and_its_maps(root, server):
    base, www = server
    (www / "api" / "v2").mkdir(parents=True)
    (www / "dl").mkdir()
    members = {f"Fake001_1K-PNG_{suffix}.png": content(suffix) for suffix in
               ("Color", "NormalGL", "NormalDX", "Roughness", "AmbientOcclusion", "Displacement")}
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as zf:
        for name, data in members.items():
            zf.writestr(name, data)
    (www / "dl" / "Fake001_1K-PNG.zip").write_bytes(buffer.getvalue())
    downloads = [{"attribute": attr, "downloadLink": f"{base}/dl/Fake001_{attr}.zip", "fileName": f"Fake001_{attr}.zip",
                  "size": len(buffer.getvalue()) if attr == "1K-PNG" else 1} for attr in ("1K-JPG", "1K-PNG", "2K-PNG")]
    asset = {"assetId": "Fake001", "displayName": "Fake 001", "shortLink": "https://ambientcg.com/a/Fake001",
             "downloadFolders": {"default": {"downloadFiletypeCategories": {"zip": {"downloads": downloads}}}}}
    (www / "api" / "v2" / "full_json").write_text(json.dumps({"foundAssets": [asset]}))
    assert run("--add", "ambientcg:Fake001", "--res", "1k", "--displacement", "--root", root) == 0

    new = [e for e in manifest(root)["entries"] if e["source"] == "ambientcg"][0]
    assert new["id"] == "Fake001" and new["title"] == "Fake 001" and new["licence"] == "CC0"
    assert new["archive"] == {"name": "Fake001_1K-PNG.zip", "url": f"{base}/dl/Fake001_1K-PNG.zip",
                              "sha256": hashlib.sha256(buffer.getvalue()).hexdigest(),
                              "bytes": len(buffer.getvalue())}
    assert [f["name"] for f in new["files"]] == ["Fake001_1K-PNG_Color.png", "Fake001_1K-PNG_NormalGL.png",
                                                 "Fake001_1K-PNG_Roughness.png", "Fake001_1K-PNG_AmbientOcclusion.png",
                                                 "Fake001_1K-PNG_Displacement.png"]
    folder = root / THIRD_PARTY / "ambientcg" / "Fake001"
    assert sorted(p.name for p in folder.iterdir()) == sorted(f["name"] for f in new["files"])  # no NormalDX, no zip
    for f in new["files"]:
        assert (folder / f["name"]).read_bytes() == members[f["name"]] and f["member"] == f["name"]
    assert run("--verify", "--root", root) == 0

    (folder / "Fake001_1K-PNG_Roughness.png").unlink()  # fetch re-downloads the pinned zip and extracts the map
    assert run("Fake001", "--verify", "--root", root) == 0
    assert not list(folder.glob("*.zip*"))


